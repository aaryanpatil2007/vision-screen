"""Photorefraction on REAL pupil images with known ground truth.

Module 3 reports 0.027 D mean spherical-equivalent error — the most precise
claim in the project, and the least tested against real imagery. The Hirschberg
module made a similar claim (0.60 PD) and degraded twelvefold on real
photographs, so this applies the same test: composite a crescent of *known*
defocus onto a real pupil region and see what the production measurement path
recovers.

The crescent is generated by the same optical model the measurement inverts, so
this does not validate the optics. What it does test is everything real imagery
adds: pupil boundaries that are not perfect circles, iris texture that is not
uniform, sensor noise, blur, eyelid occlusion, and pre-existing highlights.
"""
from __future__ import annotations

import json
from pathlib import Path

import cv2
import numpy as np

from visionscreen.modules.photoref import measure_reflex
from visionscreen.synth.eyes2d import HVID_MM
from visionscreen.synth.photoref import BASE, BRIGHT, meridional_defocus

CORPUS = Path("data/corpus/real")
RESULTS = Path("results/real_photoref.json")
PUPIL_CLASS, IRIS_CLASS = 3, 2
SPHERES = [-4.0, -3.0, -2.0, 2.0, 3.0, 4.0]
E_M, D_M = 0.005, 0.5


def _pupil_from_mask(mask: np.ndarray):
    ys, xs = np.nonzero(mask == PUPIL_CLASS)
    if len(xs) < 30:
        return None
    r = float(np.sqrt(len(xs) / np.pi))
    return (float(xs.mean()), float(ys.mean())), r


def _iris_diameter(mask: np.ndarray) -> float:
    disk = (mask == IRIS_CLASS) | (mask == PUPIL_CLASS) | (mask == 4)
    n = int(disk.sum())
    return 2.0 * float(np.sqrt(n / np.pi)) if n else 0.0


def inject_crescent(crop: np.ndarray, center, radius: float, S: float,
                    px_per_m: float) -> np.ndarray:
    """Paint an eccentric-photorefraction crescent onto a real pupil region.

    Uses the same width relation as the renderer, applied to the actual pupil
    location found in the image rather than a drawn disk.
    """
    out = crop.astype(np.float32).copy()
    h, w = out.shape[:2]
    cx, cy = center
    ys, xs = np.mgrid[0:h, 0:w].astype(np.float32)
    dx, dy = xs - cx, ys - cy
    rho = np.hypot(dx, dy)
    in_pupil = rho <= radius
    if not in_pupil.any():
        return crop.copy()

    # a red reflex fills the pupil with a dim glow before the crescent
    out[in_pupil] = BASE
    side = 1.0 if S < 0 else -1.0
    theta = np.degrees(np.arctan2(dy, dx))
    A = meridional_defocus(S, 0.0, 0.0, theta)
    r_m = radius / px_per_m
    with np.errstate(divide="ignore", invalid="ignore"):
        w_m = 2.0 * r_m - E_M / (D_M * np.abs(A))
    w_px = np.clip(np.nan_to_num(w_m), 0.0, 2.0 * r_m) * px_per_m
    bright = in_pupil & (w_px > 0.5) & (side * dx >= radius - w_px)
    out[bright] = BRIGHT
    return np.clip(out, 0, 255).astype(np.uint8)


def run(n_crops: int = 250, seed: int = 9) -> dict:
    img_dir, mask_dir = CORPUS / "images", CORPUS / "masks"
    if not img_dir.is_dir():
        raise SystemExit("build the real corpus first")
    paths = sorted(img_dir.glob("*.png"))
    rng = np.random.default_rng(seed)
    if len(paths) > n_crops:
        paths = [paths[i] for i in rng.choice(len(paths), n_crops, replace=False)]

    per_sphere: dict[float, list[float]] = {s: [] for s in SPHERES}
    detected = {s: 0 for s in SPHERES}
    attempts = 0
    null_measured = 0

    for p in paths:
        mp = mask_dir / p.name
        if not mp.exists():
            continue
        crop = cv2.imread(str(p), cv2.IMREAD_GRAYSCALE)
        mask = cv2.imread(str(mp), cv2.IMREAD_GRAYSCALE)
        if crop is None or mask is None:
            continue
        pupil = _pupil_from_mask(mask)
        iris_d = _iris_diameter(mask)
        if pupil is None or iris_d < 12:
            continue
        center, radius = pupil
        if radius < 4:
            continue
        attempts += 1
        px_per_m = iris_d / (HVID_MM / 1000.0)

        # NULL: the untouched real crop, where any estimate is an artifact
        if measure_reflex(crop, center, radius, e_m=E_M, d_m=D_M,
                          px_per_m=px_per_m) is not None:
            null_measured += 1

        for S in SPHERES:
            img = inject_crescent(crop, center, radius, S, px_per_m)
            est = measure_reflex(img, center, radius, e_m=E_M, d_m=D_M,
                                 px_per_m=px_per_m)
            if est is None:
                continue
            detected[S] += 1
            se_est = est[0] + est[1] / 2.0
            per_sphere[S].append(abs(se_est - S))

    rows = []
    for S in SPHERES:
        errs = per_sphere[S]
        rows.append({
            "sphere_d": S,
            "n": len(errs),
            "detection_rate": round(detected[S] / attempts, 3) if attempts else 0.0,
            "mean_abs_error_d": round(float(np.mean(errs)), 3) if errs else None,
            "p90_abs_error_d": round(float(np.percentile(errs, 90)), 3) if errs else None,
        })
    allerr = [e for S in SPHERES for e in per_sphere[S]]
    return {
        "crops_used": attempts,
        "rows": rows,
        "mean_abs_error_d": round(float(np.mean(allerr)), 3) if allerr else None,
        "null_measured_rate": round(null_measured / attempts, 3) if attempts else 0.0,
        "synthetic_reference_d": 0.027,
    }


def main() -> None:
    r = run()
    Path("results").mkdir(exist_ok=True)
    RESULTS.write_text(json.dumps(r, indent=2))
    print(f"Photorefraction on REAL pupils with injected known defocus "
          f"({r['crops_used']} crops)\n")
    print("| true sphere | detection | mean abs err | p90 |")
    print("|---|---|---|---|")
    for row in r["rows"]:
        print(f"| {row['sphere_d']:+.1f} D | {row['detection_rate']:.2f} | "
              f"{row['mean_abs_error_d']} D | {row['p90_abs_error_d']} D |")
    print(f"\noverall mean absolute error: {r['mean_abs_error_d']} D")
    print(f"synthetic-image reference:   {r['synthetic_reference_d']} D")
    print(f"\nNULL (untouched real crop, any estimate is an artifact): "
          f"{r['null_measured_rate']:.0%} produced one")


if __name__ == "__main__":
    main()
